/** A sidebar group with its German label; a label without a German entry fails the build. */
function group(label, items) {
  const de = sidebarLabels[label];
  if (!de) {
    throw new Error(`sidebar group "${label}" has no German label in src/sidebar-labels.mjs`);
  }
  return { label, translations: { de }, items };
}

