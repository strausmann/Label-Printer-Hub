"""Guard: own files carry the SPDX header inline wherever their format allows a comment.

``reuse lint`` (CI job ``reuse``) proves that every file has copyright and licence
information, but it also accepts an entry in ``REUSE.toml``. This test closes that gap: a
tracked file whose suffix or name allows a comment must carry the two header lines in its
first lines, unless ``REUSE.toml`` covers it. Each annotation in ``REUSE.toml`` must say in a
TOML comment why the file cannot carry an inline header (front matter, generated by a
script, byte copy of a source, data format, third-party file).

What it does NOT check: whether the copyright holder in a header is right, or whether a
``REUSE.toml`` entry is wider than it needs to be. Empty files are skipped, as ``reuse``
skips them. The exclusions are read from ``REUSE.toml`` and not repeated here, so the two
cannot drift apart.
"""

from __future__ import annotations

import json
import re
import subprocess
import tomllib
from functools import cache
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
REUSE_TOML = REPO / "REUSE.toml"

# REUSE-IgnoreStart
HEADER_COPYRIGHT = "SPDX-FileCopyrightText: 2026 Björn Strausmann and Labelyard contributors"
HEADER_LICENCE = "SPDX-License-Identifier: AGPL-3.0-or-later"
# REUSE-IgnoreEnd

HEADER_WINDOW = 6

COMMENTABLE_SUFFIXES = frozenset(
    {
        ".astro",
        ".cjs",
        ".css",
        ".html",
        ".ini",
        ".js",
        ".mako",
        ".md",
        ".mjs",
        ".py",
        ".runtime",
        ".sh",
        ".toml",
        ".ts",
        ".tsx",
        ".yaml",
        ".yml",
    }
)
COMMENTABLE_NAMES = frozenset(
    {
        ".dockerignore",
        ".editorconfig",
        ".env.example",
        ".gitignore",
        "CODEOWNERS",
        "Dockerfile",
        "Makefile",
    }
)

JSON_FILES = (
    "licence-policy.yml",
    "docs/licence-test-vectors.json",
    "frontend/public/manifest.webmanifest",
    "backend/licences/extra-records.json",
)

THIRD_PARTY = (
    "backend/app/page_render/fonts/AtkinsonHyperlegibleNext-Variable.ttf",
    "backend/app/page_render/fonts/DejaVuSans.ttf",
    "backend/app/page_render/fonts/IBMPlexMono-Bold.ttf",
    "backend/app/page_render/fonts/LICENSE-AtkinsonHyperlegibleNext-OFL.txt",
    "backend/app/page_render/fonts/LICENSE-DejaVu.txt",
    "backend/app/page_render/fonts/LICENSE-IBMPlexMono-OFL.txt",
    "CODE_OF_CONDUCT.md",
    "LICENSE",
)


def _glob_to_regex(pattern: str) -> re.Pattern[str]:
    """REUSE.toml globbing: ``*`` stays inside one path segment, ``**`` crosses them."""
    out = []
    i = 0
    while i < len(pattern):
        if pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern.startswith("\\*", i):
            out.append(re.escape("*"))
            i += 2
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out) + r"\Z")


@cache
def _annotations() -> list[dict[str, object]]:
    data = tomllib.loads(REUSE_TOML.read_text(encoding="utf-8"))
    annotations = data["annotations"]
    assert isinstance(annotations, list)
    return annotations


@cache
def _reuse_toml_only() -> tuple[re.Pattern[str], ...]:
    patterns: list[re.Pattern[str]] = []
    for ann in _annotations():
        paths = ann["path"]
        for path in [paths] if isinstance(paths, str) else paths:  # type: ignore[union-attr]
            patterns.append(_glob_to_regex(str(path)))
    return tuple(patterns)


def _covered_by_reuse_toml(path: str) -> bool:
    return any(p.match(path) for p in _reuse_toml_only())


@cache
def _tracked() -> tuple[str, ...]:
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=REPO, check=True, capture_output=True
    ).stdout.decode("utf-8")
    return tuple(p for p in out.split("\0") if p and (REPO / p).is_file())


def _commentable(path: str) -> bool:
    p = Path(path)
    return p.name in COMMENTABLE_NAMES or p.suffix in COMMENTABLE_SUFFIXES


def test_own_sources_carry_header() -> None:
    missing = []
    for path in _tracked():
        if not _commentable(path) or _covered_by_reuse_toml(path):
            continue
        file = REPO / path
        if file.stat().st_size == 0:
            continue
        head = file.read_text(encoding="utf-8").splitlines()[:HEADER_WINDOW]
        text = "\n".join(head)
        if HEADER_COPYRIGHT not in text or HEADER_LICENCE not in text:
            missing.append(path)
    assert not missing, "SPDX header missing in the first lines of:\n" + "\n".join(missing)


def test_reuse_toml_annotations_explain_why() -> None:
    """Every ``[[annotations]]`` block is preceded by a TOML comment that gives the reason."""
    lines = REUSE_TOML.read_text(encoding="utf-8").splitlines()
    unexplained = []
    for i, line in enumerate(lines):
        if line.strip() != "[[annotations]]":
            continue
        before = lines[i - 1].strip() if i else ""
        if not before.startswith("#"):
            unexplained.append(f"REUSE.toml:{i + 1}")
    assert len(_annotations()) > 0
    assert not unexplained, "annotation without a reason comment: " + ", ".join(unexplained)


def test_reuse_toml_globs_match_tracked_files() -> None:
    """A stale glob would silently stop covering anything; every path must match a file."""
    tracked = _tracked()
    stale = [p.pattern for p in _reuse_toml_only() if not any(p.match(t) for t in tracked)]
    assert not stale, "REUSE.toml paths matching no tracked file: " + ", ".join(stale)


def test_json_files_stay_json() -> None:
    for path in JSON_FILES:
        json.loads((REPO / path).read_text(encoding="utf-8"))


def test_third_party_files_not_relicensed() -> None:
    for path in THIRD_PARTY:
        head = (REPO / path).read_bytes()[:4096]
        assert b"AGPL-3.0-or-later" not in head or path == "LICENSE", path
        assert HEADER_COPYRIGHT.encode() not in head, path
        assert _covered_by_reuse_toml(path), path
    by_path = {}
    for ann in _annotations():
        paths = ann["path"]
        for p in [paths] if isinstance(paths, str) else paths:  # type: ignore[union-attr]
            by_path[str(p)] = ann
    for path in THIRD_PARTY:
        if path == "LICENSE":
            continue
        ann = next(a for g, a in by_path.items() if _glob_to_regex(g).match(path))
        assert ann.get("precedence") == "override", path
        assert "AGPL" not in str(ann["SPDX-License-Identifier"]), path
